/**
 * The app mark. Solid rather than stroked, because it stands in for a logo and
 * is the same skyline as the installed home-screen icon, so the two read as one
 * identity. Sized by className like every other icon.
 */
export function AppMark({ className = 'h-5 w-5' }) {
    return (
        <svg viewBox="0 0 64 64" className={className} aria-hidden="true" focusable="false">
            <g fill="currentColor">
                <rect x="12" y="30" width="13" height="22" />
                <rect x="27" y="14" width="14" height="38" />
                <rect x="43" y="23" width="13" height="29" />
            </g>
        </svg>
    );
}

export default function Icon({ name, className = 'h-5 w-5', strokeWidth = 1.5, ...rest }) {
    const d = PATHS[name];

    if (!d) {
        return null;
    }

    return (
        <svg
            viewBox="0 0 24 24"
            fill="none"
            stroke="currentColor"
            strokeWidth={strokeWidth}
            strokeLinecap="round"
            strokeLinejoin="round"
            className={className}
            aria-hidden="true"
            focusable="false"
            {...rest}
        >
            {/* Split so multi-shape icons (camera, map pin) render as separate
                subpaths rather than one accidentally-joined outline. */}
            {d.split(' M').map((segment, i) => (
                <path key={i} d={i === 0 ? segment : `M${segment}`} />
            ))}
        </svg>
    );
}
